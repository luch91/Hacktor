import { chromium, expect } from '@playwright/test';
import { copyFile, mkdir, writeFile } from 'node:fs/promises';

const baseURL = process.env.HACKTOR_LOCAL_URL || 'http://127.0.0.1:8791';
const executablePath = process.env.HACKTOR_BROWSER_EXECUTABLE;
const output = 'docs/evidence/m2d';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(executablePath ? { executablePath } : {}), args: ['--no-sandbox', '--disable-dev-shm-usage'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, recordVideo: { dir: output, size: { width: 1440, height: 900 } } });
const page = await context.newPage();
const shot = async (name, fullPage = true) => page.screenshot({ path: `${output}/${name}.png`, fullPage, animations: 'disabled' });
try {
  await page.goto(baseURL);
  await shot('landing-dark');
  await page.getByRole('radio', { name: 'light' }).check();
  await shot('landing-light');
  await page.getByRole('radio', { name: 'dark' }).check();
  await page.getByRole('button', { name: /Start with an idea/ }).click();
  await page.getByLabel('Workspace title').fill('Neighborhood care sprint');
  await page.getByLabel('Original idea').fill('An offline neighborhood mutual aid board that coordinates one request at a time.');
  await page.getByRole('button', { name: 'Review context' }).click();
  await page.getByRole('button', { name: 'Confirm context and enter Studio' }).click();
  await page.getByRole('button', { name: 'Generate diverse slate' }).click();
  await page.locator('.graph-node').first().waitFor();
  await shot('studio-constellation');
  await page.locator('.constellation').screenshot({ path: `${output}/constellation-entire-graph.png`, animations: 'disabled' });
  const geometry = await page.locator('.graph-node').evaluateAll((nodes) => nodes.map((node) => { const r = node.getBoundingClientRect(); return { id: node.textContent?.slice(0, 40), left: r.left, top: r.top, right: r.right, bottom: r.bottom }; }));
  await writeFile(`${output}/geometry.json`, JSON.stringify({ viewport: 1440, nodes: geometry }, null, 2));
  await page.locator('.graph-node').nth(1).click();
  await shot('selected-idea-inspector');
  await page.getByRole('button', { name: 'List view' }).click();
  await shot('studio-list');
  await page.getByRole('button', { name: 'Branch' }).click();
  await page.getByRole('button', { name: 'Constellation' }).click();
  await expect(page.locator('.graph-node')).toHaveCount(10);
  await expect(page.locator('.graph-node.selected')).toContainText('Branch');
  await shot('evolved-branch');
  await page.locator('.constellation').screenshot({ path: `${output}/branch-entire-graph.png`, animations: 'disabled' });
  await page.getByLabel('Second idea').selectOption({ index: 1 });
  await page.getByRole('button', { name: 'Combine selected versions' }).click();
  await expect(page.locator('.graph-node')).toHaveCount(11);
  await expect(page.locator('.graph-node.selected')).toContainText('Two-parent combination');
  await shot('two-parent-combination');
  await page.locator('.constellation').screenshot({ path: `${output}/combination-entire-graph.png`, animations: 'disabled' });
  await page.setViewportSize({ width: 2200, height: 1000 });
  await page.locator('.constellation-scroll').evaluate((element) => { element.style.maxHeight = 'none'; element.style.overflow = 'visible'; });
  await shot('combination-overview');
  await page.locator('.constellation-scroll').evaluate((element) => { element.style.maxHeight = ''; element.style.overflow = ''; });
  await page.setViewportSize({ width: 768, height: 1024 });
  await shot('tablet-studio');
  await page.setViewportSize({ width: 320, height: 800 });
  await page.getByRole('button', { name: 'Explore ideas' }).click();
  await page.locator('.graph-node.selected').scrollIntoViewIfNeeded();
  await shot('mobile-320-studio');
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await mobile.goto(baseURL);
  await mobile.screenshot({ path: `${output}/mobile-390-landing.png`, fullPage: true, animations: 'disabled' });
  await mobile.close();
  console.log('Captured actual Worker-backed application at', baseURL);
} finally {
  const video = page.video();
  await context.close();
  if (video) await copyFile(await video.path(), `${output}/interaction.webm`);
  await browser.close();
}
